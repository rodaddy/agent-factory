/**
 * @module hostedapp/emit
 * @description Builders for the individual k3s-deploy files a rendered target
 *   is made of. Each function is pure: merged declaration plus render context
 *   in, one YAML document string out. The shapes mirror the hand-written
 *   directories in `rtech/k3s-deploy` (`bb-landing`, `openseo`, `mcp2cli`), so
 *   `scripts/sop-gate/check-render.sh` renders and schema-validates the output
 *   the same way it does a human's.
 *
 * @outputs
 *   - `RenderContext` -- the identity every builder needs
 *   - `application`, `namespace`, `deployment`, `service`, `route`, `pvc`,
 *     `cronjob`, `configmap`, `kustomization`, `manifestNotes`
 *
 * @dependencies
 *   - yaml -- document serialization
 *   - ./schema -- the validated declaration type
 *   - ../log -- the one logger, for the traced() wrapper
 */
import { stringify } from "yaml";
import { traced } from "../log";
import type { Declaration } from "./schema";

/** Identity and provenance shared by every file of one rendered target. */
export type RenderContext = {
	/** The application name from the declaration. */
	name: string;
	/** The target being rendered, e.g. `uat`. */
	target: string;
	/** `<name>-<target>`: the namespace, the Application name, the workload name. */
	slug: string;
	/** The accepted image reference, tag and digest included. */
	image: string;
	/** `<owner>/<repo>` the declaration came from. */
	repo: string;
	/** The accepted 40-hex commit sha. */
	ref: string;
	/** The accepted declaration sha256. */
	hash: string;
	/** True when the registry entry is not `active`; scales to zero. */
	paused: boolean;
};

const K8S_NAME = "app.kubernetes.io/name";
const REGISTRY_HEADER = "generated by software-factory hosted-app render";

/** A generated resource name that no Kubernetes object could carry. */
export class RenderError extends Error {
	constructor(
		readonly path: string,
		message: string,
	) {
		super(message);
		this.name = "RenderError";
	}
}

/** DNS-1123 subdomain bound; a CronJob's Jobs append `-<11 digits>`. */
const NAME_MAX = 63;
const CRONJOB_MAX = 52;

/**
 * The one place a generated resource name is built.
 *
 * Each component is schema-valid on its own, but the emitted name is
 * `<app>-<target>-<component>`, so a valid declaration can still exceed the
 * Kubernetes bound. Checking here — rather than loosening or tightening the
 * schema, which cannot see the target it will be rendered for — keeps the
 * limit at the boundary that actually knows the final string.
 *
 * @param parts - the name segments, joined with `-`
 * @param path - the declaration path to name in the problem
 * @param max - the bound; `CRONJOB_MAX` where a Job suffix is appended
 * @throws RenderError when the joined name exceeds `max`
 */
export const resourceName = traced(
	"hostedapp.resourceName",
	function resourceName(parts: readonly string[], path: string, max = NAME_MAX): string {
		const name = parts.join("-");
		if (name.length > max) {
			throw new RenderError(
				path,
				`generated name ${name} is ${name.length} characters, over the ${max}-character Kubernetes limit`,
			);
		}
		return name;
	},
);

/** The provenance header every emitted file carries, as `# ` comment lines. */
export const header = traced(
	"hostedapp.header",
	function header(ctx: RenderContext, what: string): string {
		return [
			`# ${ctx.slug} — ${what}.`,
			"#",
			`# ${REGISTRY_HEADER} from ${ctx.repo}@${ctx.ref},`,
			`# declaration sha256 ${ctx.hash}.`,
			"#",
			"# Edit the declaration, not this file: the next render overwrites it.",
			"",
		].join("\n");
	},
);

/** Serialize one object as a YAML document under `head`. */
function doc(head: string, value: unknown): string {
	return `${head}---\n${stringify(value, { lineWidth: 0 })}`;
}

/** Join several objects into one multi-document YAML file under `head`. */
function docs(head: string, values: readonly unknown[]): string {
	return head + values.map((v) => `---\n${stringify(v, { lineWidth: 0 })}`).join("");
}

/** Standard labels: one identity, carried by every object of the target. */
function labels(ctx: RenderContext): Record<string, string> {
	return { [K8S_NAME]: ctx.slug, "app.kubernetes.io/part-of": ctx.name };
}

/** The Argo Application file, flat in `apps/`. */
export const application = traced(
	"hostedapp.application",
	function application(ctx: RenderContext): string {
		return doc(header(ctx, "Argo Application"), {
			apiVersion: "argoproj.io/v1alpha1",
			kind: "Application",
			metadata: {
				name: ctx.slug,
				namespace: "argocd",
				finalizers: ["resources-finalizer.argocd.argoproj.io"],
			},
			spec: {
				project: "default",
				source: {
					repoURL: "http://10.0.20.58:3000/rtech/k3s-deploy.git",
					targetRevision: "main",
					path: `manifests/apps/${ctx.slug}`,
				},
				destination: { server: "https://kubernetes.default.svc", namespace: ctx.slug },
				syncPolicy: {
					automated: { prune: true, selfHeal: true },
					syncOptions: ["CreateNamespace=true"],
				},
			},
		});
	},
);

/** The target's own Namespace — the only cluster-scoped object emitted. */
export const namespace = traced(
	"hostedapp.namespace",
	function namespace(ctx: RenderContext): string {
		return doc(header(ctx, "namespace"), {
			apiVersion: "v1",
			kind: "Namespace",
			metadata: { name: ctx.slug, labels: labels(ctx) },
		});
	},
);

/** Container env: declared values, then secret keys, then the database URI. */
function containerEnv(decl: Declaration, ctx: RenderContext): unknown[] {
	const env: unknown[] = Object.entries(decl.runtime.env).map(([name, value]) => ({
		name,
		value: String(value),
	}));
	for (const secret of decl.secrets) {
		for (const key of secret.keys) {
			env.push({ name: key, valueFrom: { secretKeyRef: { name: secret.name, key } } });
		}
	}
	if (decl.database !== undefined) {
		env.push({
			name: decl.database.env_key,
			valueFrom: { secretKeyRef: { name: `${ctx.slug}-db`, key: "uri" } },
		});
	}
	return env;
}

/** Volume mounts and volumes for storage claims and mounted config files. */
function volumes(decl: Declaration, ctx: RenderContext): { mounts: unknown[]; volumes: unknown[] } {
	const mounts: unknown[] = [];
	const vols: unknown[] = [];
	for (const store of decl.storage) {
		mounts.push({ name: store.name, mountPath: store.mount });
		vols.push({
			name: store.name,
			persistentVolumeClaim: {
				claimName: resourceName([ctx.slug, store.name], `storage.${store.name}`),
			},
		});
	}
	for (const file of decl.config_files) {
		const key = file.mount.split("/").pop() ?? file.name;
		mounts.push({ name: file.name, mountPath: file.mount, subPath: key, readOnly: true });
		vols.push({
			name: file.name,
			configMap: { name: resourceName([ctx.slug, file.name], `config_files.${file.name}`) },
		});
	}
	return { mounts, volumes: vols };
}

/** One HTTP probe against a named container port. */
function probe(
	path: string,
	port: string,
	periodSeconds: number,
	failureThreshold: number,
): unknown {
	return { httpGet: { path, port }, periodSeconds, failureThreshold };
}

/**
 * The container ports, and the port name the probes address.
 *
 * `runtime.health.port` may name a port the service does not publish — a
 * health endpoint on its own listener. When it differs from `runtime.port`
 * that port has to exist on the container for a probe to reach it, so a
 * second named port is emitted and the probes point at it.
 */
function ports(decl: Declaration): { ports: unknown[]; probePort: string } {
	const list: unknown[] = [{ name: "http", containerPort: decl.runtime.port, protocol: "TCP" }];
	const health = decl.runtime.health.port;
	if (health === undefined || health === decl.runtime.port) {
		return { ports: list, probePort: "http" };
	}
	list.push({ name: "health", containerPort: health, protocol: "TCP" });
	return { ports: list, probePort: "health" };
}

/** The Deployment: one container, probes from `runtime.health`, pinned image. */
export const deployment = traced(
	"hostedapp.deployment",
	function deployment(decl: Declaration, ctx: RenderContext): string {
		const selector = { [K8S_NAME]: ctx.slug };
		const vol = volumes(decl, ctx);
		const port = ports(decl);
		const container: Record<string, unknown> = {
			name: ctx.name,
			image: ctx.image,
			imagePullPolicy: "IfNotPresent",
			ports: port.ports,
			env: containerEnv(decl, ctx),
			startupProbe: probe(decl.runtime.health.path, port.probePort, 5, 30),
			readinessProbe: probe(decl.runtime.health.path, port.probePort, 10, 3),
			livenessProbe: probe(decl.runtime.health.path, port.probePort, 30, 3),
			resources: decl.runtime.resources,
			securityContext: {
				allowPrivilegeEscalation: false,
				capabilities: { drop: ["ALL"] },
			},
		};
		if (decl.runtime.command.length > 0) container.command = decl.runtime.command;
		if (vol.mounts.length > 0) container.volumeMounts = vol.mounts;
		const spec: Record<string, unknown> = {
			imagePullSecrets: [{ name: `${ctx.name}-regcred` }],
			containers: [container],
		};
		if (vol.volumes.length > 0) spec.volumes = vol.volumes;
		return doc(header(ctx, "workload"), {
			apiVersion: "apps/v1",
			kind: "Deployment",
			metadata: { name: ctx.slug, namespace: ctx.slug, labels: labels(ctx) },
			spec: {
				// A paused registry entry scales to zero rather than being deleted, so
				// the namespace, its claims and its Secrets survive the pause.
				replicas: ctx.paused ? 0 : decl.runtime.replicas,
				revisionHistoryLimit: 5,
				selector: { matchLabels: selector },
				template: { metadata: { labels: labels(ctx) }, spec },
			},
		});
	},
	// BOTH ENDS, and this is the sharpest case in the module. `containerEnv` copies
	// `decl.runtime.env` VALUES literally into the container's `env:` list, so the
	// returned YAML carries every operator-set env value in plaintext -- a
	// `STRIPE_SK`-shaped key survives summarize() (probed in validate.ts). Declared
	// `secrets` and `database` go in as `secretKeyRef` NAMES, which are safe, but
	// the env bag beside them is not, and one manifest string holds both.
	{ redact: { args: [0], result: true } },
);

/** The ClusterIP Service: port 80 in front of the container's `http` port. */
export const service = traced(
	"hostedapp.service",
	function service(_decl: Declaration, ctx: RenderContext): string {
		return doc(header(ctx, "service"), {
			apiVersion: "v1",
			kind: "Service",
			metadata: { name: ctx.slug, namespace: ctx.slug, labels: labels(ctx) },
			spec: {
				type: "ClusterIP",
				selector: { [K8S_NAME]: ctx.slug },
				ports: [{ name: "http", port: 80, targetPort: "http", protocol: "TCP" }],
			},
		});
	},
	// ARG 0 ONLY. The declaration is `_decl` -- deliberately UNUSED here, so nothing
	// from it reaches the Service or the result, which is built from `ctx` alone.
	// Masking it costs nothing and keeps the env bag off the `.enter` line.
	{ redact: { args: [0] } },
);

/** A cert-manager Certificate for the public hosts, or none when all private. */
function certificate(hosts: readonly string[], ctx: RenderContext): unknown | undefined {
	if (hosts.length === 0) return undefined;
	return {
		apiVersion: "cert-manager.io/v1",
		kind: "Certificate",
		metadata: { name: `${ctx.slug}-tls`, namespace: ctx.slug },
		spec: {
			secretName: `${ctx.slug}-tls`,
			commonName: hosts[0],
			dnsNames: [...hosts],
			privateKey: { algorithm: "ECDSA", size: 256, rotationPolicy: "Always" },
			issuerRef: { name: "letsencrypt", kind: "ClusterIssuer", group: "cert-manager.io" },
		},
	};
}

/**
 * The Traefik route. A Certificate is emitted only for `public: true` hosts:
 * a private zone has no ACME solver, so requesting a cert for one creates a
 * Certificate that never goes Ready and reports no error.
 */
export const route = traced(
	"hostedapp.route",
	function route(decl: Declaration, ctx: RenderContext): string {
		const publicHosts = decl.hostnames.filter((h) => h.public).map((h) => h.host);
		const privateHosts = decl.hostnames.filter((h) => !h.public).map((h) => h.host);
		const cert = certificate(publicHosts, ctx);
		const out: unknown[] = [];
		if (cert !== undefined) out.push(cert);
		// One route per visibility class. A single route over a mixed host list
		// would serve the private hosts under the public Certificate, which names
		// only the public SANs; the private hosts fall back to Traefik's default.
		if (publicHosts.length > 0) {
			out.push(ingressRoute(ctx, publicHosts, ctx.slug, { secretName: `${ctx.slug}-tls` }));
		}
		if (privateHosts.length > 0) {
			const name =
				publicHosts.length > 0 ? resourceName([ctx.slug, "internal"], "hostnames") : ctx.slug;
			out.push(ingressRoute(ctx, privateHosts, name, {}));
		}
		return docs(header(ctx, "route"), out);
	},
	// ARG 0 ONLY. The route is built from `decl.hostnames` -- DNS names, which are
	// not secrets and are the useful content of this trace, so the RESULT stays
	// visible. Arg 0 is masked because it is the whole declaration, env bag
	// included, not because routes are sensitive.
	{ redact: { args: [0] } },
);

/** One Traefik IngressRoute over `hosts`, with the given `tls` block. */
function ingressRoute(
	ctx: RenderContext,
	hosts: readonly string[],
	name: string,
	tls: Record<string, unknown>,
): unknown {
	return {
		apiVersion: "traefik.io/v1alpha1",
		kind: "IngressRoute",
		metadata: { name, namespace: ctx.slug },
		spec: {
			entryPoints: ["websecure"],
			routes: [
				{
					kind: "Rule",
					match: hosts.map((h) => `Host(\`${h}\`)`).join(" || "),
					services: [{ name: ctx.slug, port: 80 }],
				},
			],
			tls,
		},
	};
}

/** One Longhorn claim per declared storage entry. */
export const pvc = traced(
	"hostedapp.pvc",
	function pvc(decl: Declaration, ctx: RenderContext): string {
		return docs(
			header(ctx, "persistent volume claims"),
			decl.storage.map((store) => ({
				apiVersion: "v1",
				kind: "PersistentVolumeClaim",
				metadata: {
					name: resourceName([ctx.slug, store.name], `storage.${store.name}`),
					namespace: ctx.slug,
					annotations: { "argocd.argoproj.io/sync-options": "Prune=false" },
					labels: labels(ctx),
				},
				spec: {
					accessModes: ["ReadWriteOnce"],
					storageClassName: "longhorn",
					resources: { requests: { storage: store.size } },
				},
			})),
		);
	},
	// ARG 0 ONLY. Claims are built from `decl.storage` -- a name, a mount path and
	// a size -- so the RESULT is safe and worth seeing. Arg 0 is the whole
	// declaration, so it is masked on the same rule as the other builders.
	{ redact: { args: [0] } },
);

/** One CronJob per declared entry, suspended while the entry is paused. */
export const cronjob = traced(
	"hostedapp.cronjob",
	function cronjob(decl: Declaration, ctx: RenderContext): string {
		return docs(
			header(ctx, "scheduled jobs"),
			decl.cron.map((job) => ({
				apiVersion: "batch/v1",
				kind: "CronJob",
				metadata: {
					name: resourceName([ctx.slug, job.name], `cron.${job.name}`, CRONJOB_MAX),
					namespace: ctx.slug,
					labels: labels(ctx),
				},
				spec: {
					schedule: job.schedule,
					suspend: ctx.paused,
					concurrencyPolicy: "Forbid",
					successfulJobsHistoryLimit: 1,
					failedJobsHistoryLimit: 3,
					jobTemplate: {
						spec: {
							ttlSecondsAfterFinished: 3600,
							backoffLimit: 1,
							template: {
								metadata: { labels: labels(ctx) },
								spec: {
									restartPolicy: "Never",
									imagePullSecrets: [{ name: `${ctx.name}-regcred` }],
									containers: [
										{
											name: job.name,
											image: ctx.image,
											command: job.command,
											env: containerEnv(decl, ctx),
											resources: decl.runtime.resources,
										},
									],
								},
							},
						},
					},
				},
			})),
		);
	},
	// BOTH ENDS, same reason as `deployment`: each CronJob's container calls
	// `containerEnv(decl, ctx)`, so `decl.runtime.env` VALUES are interpolated into
	// the returned YAML in plaintext. The job's `command` array is operator-authored
	// too, and a scheduled command is a normal place to find a flag value.
	{ redact: { args: [0], result: true } },
);

/** One ConfigMap per config file, holding the content read from the repo. */
export const configmap = traced(
	"hostedapp.configmap",
	function configmap(
		decl: Declaration,
		ctx: RenderContext,
		contents: ReadonlyMap<string, string>,
	): string {
		return docs(
			header(ctx, "mounted configuration"),
			decl.config_files.map((file) => ({
				apiVersion: "v1",
				kind: "ConfigMap",
				metadata: {
					name: resourceName([ctx.slug, file.name], `config_files.${file.name}`),
					namespace: ctx.slug,
					labels: labels(ctx),
				},
				data: { [file.mount.split("/").pop() ?? file.name]: contents.get(file.name) ?? "" },
			})),
		);
	},
	// BOTH ENDS. Arg 2 IS the config-file content read out of the product repo, and
	// the result embeds it verbatim as ConfigMap `data` -- this function's whole job
	// is to carry those bytes, so input and output are equally sensitive. An app
	// config or values file is a normal place for a key, and nothing between the
	// fetch and here inspects it.
	{ redact: { args: [0, 2], result: true } },
);

/** The kustomization, listing every emitted manifest in a stable order. */
export const kustomization = traced(
	"hostedapp.kustomization",
	function kustomization(ctx: RenderContext, resources: readonly string[]): string {
		return doc(header(ctx, "manifest set"), {
			apiVersion: "kustomize.config.k8s.io/v1beta1",
			kind: "Kustomization",
			namespace: ctx.slug,
			resources: [...resources],
		});
	},
);

/** The operator note: what this render is, and the Secrets it needs by hand. */
export const manifestNotes = traced(
	"hostedapp.manifestNotes",
	function manifestNotes(decl: Declaration, ctx: RenderContext): string {
		const lines = [
			`# ${ctx.slug} manifests`,
			"",
			"**STATUS: WRITTEN by software-factory. Not merged, not deployed.**",
			"",
			`${REGISTRY_HEADER} from \`${ctx.repo}@${ctx.ref}\`, declaration sha256`,
			`\`${ctx.hash}\`, target \`${ctx.target}\`. Edit the declaration, not these files.`,
			"",
			"## Secrets applied out of band",
			"",
			"Secrets are never rendered into this repository. Each of the following is",
			"applied by hand into the namespace from its Vaultwarden item:",
			"",
			`- \`${ctx.name}-regcred\` (dockerconfigjson) — Forgejo registry pull credential.`,
		];
		for (const secret of decl.secrets) {
			lines.push(
				`- \`${secret.name}\` — keys ${secret.keys.map((k) => `\`${k}\``).join(", ")}, from Vaultwarden item **${secret.vaultwarden_item}**.`,
			);
		}
		if (decl.database !== undefined) {
			lines.push(
				`- \`${ctx.slug}-db\` — key \`uri\`, the ${decl.database.cluster} cluster connection string for role \`${decl.database.role}\`, from Vaultwarden item **${decl.database.password_item}**.`,
			);
		}
		lines.push("");
		return `${lines.join("\n")}`;
	},
	// ARG 0 ONLY. The note names Vaultwarden ITEM names, Secret names and KEY names
	// -- pointers to credentials, never the credentials, and that list is exactly
	// what an operator needs from this trace, so the result stays visible. Arg 0 is
	// the whole declaration, masked on the same rule as every other builder here.
	{ redact: { args: [0] } },
);
