/**
 * @module src/enroll/derive
 * @description The `enroll --derive` planner (lane 831a). Reads a
 *   k3s-deploy checkout's `manifests/apps/<dir>/` tree and returns one plan row
 *   per app dir: its image, the image's Forge owner, whether the dir is already
 *   on the tag rail (rendered by factory-workflows), and its uat/prod pairing.
 *   Pure over the filesystem: no network, no writes. Per D19 the plan feeds
 *   `enroll-app` invocations; it never produces config/repos.yml build_bump
 *   blocks. Source-repo resolution is lane 831b; the CLI is 831c.
 *
 * @outputs
 *   - `INFRA_DIRS` -- the fixed infra/third-party exclusion list
 *   - `DNS_LABEL` -- the name shape a dir must have to become a command
 *   - `isInfraDir` -- whether a dir name is on that list
 *   - `derivePlan` -- the plan rows for one k3s-deploy checkout
 *
 * @dependencies
 *   - node:fs, node:path -- read the manifests tree
 *   - ../log -- the traced() wrapper
 */
import { existsSync, readdirSync, readFileSync, statSync } from "node:fs";
import { join } from "node:path";
import { traced } from "../log";
import { DNS_LABEL_PATTERN } from "../names/dns-label";

/**
 * Infra and third-party dirs under manifests/apps that are never app
 * candidates: cluster plumbing, vendored images, and routes to services that
 * are not built from a fleet repo (p5-scout "fleet"). A trailing `*`
 * matches by prefix; every other entry matches the dir name exactly. Adding a
 * dir here removes it from the plan, so the list is fixed and reviewed.
 */
export const INFRA_DIRS: readonly string[] = [
	"alertmanager-*",
	"bifrost",
	"cloudflared",
	"cnpg-backup-store",
	"flaresolverr",
	"formbricks",
	"grafana-*",
	"job-gc",
	"listmonk",
	"llama-swap*",
	"localmail",
	"longhorn-backup",
	"monitoring",
	"n8n",
	"open-webui-route",
	"vaultwarden",
	"edge-lxc",
	"ai-inference",
	"alert-remediator",
	"collab-checkout-refresh",
	"hello",
];

/** Why a row is on or off the rail. */
export type DeriveReason = "rendered" | "hand-written" | "infra" | "no image" | "invalid-name";

/** Stage name to app dir, paired on the dir name minus its `-uat`/`-prod` suffix. */
export type EnvPairing = { uat?: string; prod?: string; default?: string };

/** One plan row per manifests/apps dir. */
export type DeriveRow = {
	dir: string;
	/** The first container image ref in deployment.yaml, verbatim; null when absent or infra. */
	image: string | null;
	/** The registry path's first segment (`<host>/<owner>/<name>`); null when not derivable. */
	owner: string | null;
	/** True when kustomization.yaml carries the factory-workflows deploy header. */
	onRail: boolean;
	envs: EnvPairing;
	reason: DeriveReason;
};

/**
 * The header factory-workflows writes at the top of every rendered file, e.g.
 * `# generated by factory-workflows deploy for rodaddy-hook-probe-uat from
 * rodaddy/hook-probe@99c83807353d; edit the source repo, ...` (copied from a
 * live k3s-deploy render).
 */
const RENDERED_HEADER = /^#\s*generated by factory-workflows deploy for (\S+) from \S+@[0-9a-f]+;/m;
const IMAGE_LINE = /^\s*(?:-\s*)?image:\s*["']?([^\s"'#]+)/m;
const STAGE_SUFFIX = /-(uat|prod)$/;
/** A Kubernetes DNS-1123 label (1-63 chars); a dir or app name failing it never reaches a printed command. */
export const DNS_LABEL = DNS_LABEL_PATTERN;

/**
 * Whether a manifests/apps dir name is on the fixed infra exclusion list.
 *
 * @param dir - the dir name under manifests/apps
 * @returns true when an exact entry or a `*` prefix entry matches
 */
export const isInfraDir = traced("enroll.isInfraDir", function isInfraDir(dir: string): boolean {
	return INFRA_DIRS.some((entry) =>
		entry.endsWith("*") ? dir.startsWith(entry.slice(0, -1)) : dir === entry,
	);
});

function readIfPresent(path: string): string | null {
	return existsSync(path) ? readFileSync(path, "utf8") : null;
}

function ownerOf(image: string): string | null {
	const segments = image.split("/");
	return segments.length >= 3 ? (segments[1] ?? null) : null;
}

function stageOf(dir: string): { base: string; stage: keyof EnvPairing } {
	const match = STAGE_SUFFIX.exec(dir);
	if (match === null) return { base: dir, stage: "default" };
	return { base: dir.slice(0, -match[0].length), stage: match[1] as "uat" | "prod" };
}

/**
 * Derive the enrolment plan from a k3s-deploy checkout.
 *
 * @param k3sDeployDir - the checkout root holding `manifests/apps/`
 * @returns one row per app dir, sorted by dir name
 * @throws when `manifests/apps` does not exist under the given root
 */
export const derivePlan = traced(
	"enroll.derivePlan",
	function derivePlan(k3sDeployDir: string): DeriveRow[] {
		const appsDir = join(k3sDeployDir, "manifests", "apps");
		if (!existsSync(appsDir) || !statSync(appsDir).isDirectory()) {
			throw new Error(`enroll --derive: no manifests/apps directory under ${k3sDeployDir}`);
		}
		const dirs = readdirSync(appsDir)
			.filter((name) => statSync(join(appsDir, name)).isDirectory())
			.sort();

		const pairings = new Map<string, EnvPairing>();
		for (const dir of dirs) {
			const { base, stage } = stageOf(dir);
			const pairing = pairings.get(base) ?? {};
			pairing[stage] = dir;
			pairings.set(base, pairing);
		}

		return dirs.map((dir): DeriveRow => {
			const envs = pairings.get(stageOf(dir).base) ?? {};
			if (!DNS_LABEL.test(dir) || !DNS_LABEL.test(stageOf(dir).base)) {
				return { dir, image: null, owner: null, onRail: false, envs, reason: "invalid-name" };
			}
			if (isInfraDir(dir)) {
				return { dir, image: null, owner: null, onRail: false, envs, reason: "infra" };
			}
			const kustomization = readIfPresent(join(appsDir, dir, "kustomization.yaml"));
			const header = kustomization === null ? null : RENDERED_HEADER.exec(kustomization);
			const onRail = header !== null && header[1] === dir;
			const deployment = readIfPresent(join(appsDir, dir, "deployment.yaml"));
			const image = deployment === null ? null : (IMAGE_LINE.exec(deployment)?.[1] ?? null);
			if (image === null) {
				return { dir, image: null, owner: null, onRail, envs, reason: "no image" };
			}
			const reason = onRail ? "rendered" : "hand-written";
			return { dir, image, owner: ownerOf(image), onRail, envs, reason };
		});
	},
);
