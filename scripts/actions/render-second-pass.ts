/**
 * @module scripts/actions/render-second-pass
 * @description Render the adversarial second pass of the `pr-review` Forgejo
 *   Actions workflow. Reads pass 1's `manifest.json` and
 *   `reply-<i>.json` files from `CHUNK_DIR` and the unified diff from
 *   `DIFF_FILE`, decides which second-pass calls to make, and writes their
 *   request bodies. It performs no network call: the workflow sends each
 *   request through `call-engine.ts`, so this module's contract is "pass-1
 *   replies plus diff in, plan plus request files out".
 *
 *   Two calls, each independent:
 *   - the REFUTER runs iff at least one chunk reply parses to `fix-first`; it
 *     carries every `fix-first` chunk's review and the diff, and tries to refute
 *     each P0/P1 finding from the diff alone;
 *   - the CHECKLIST runs iff any path in the DIFF's file headers (old or new
 *     path) sits on the factory's trust surface (`trustFiles`), or a header
 *     cannot be parsed (fail closed); it checks the diff against a fixed list.
 *   Fix-first reviews larger than `REFUTE_FINDINGS_MAX_BYTES` skip the refuter
 *   (`refute_skipped`), so the pass-1 findings stand rather than being cut.
 *
 *   Both system prompts are fixed author text. The diff and the pass-1 review
 *   text are UNTRUSTED (repository content, and engine output derived from it):
 *   they reach the engine only in the user message, inside fences,
 *   each fence one backtick longer than any run inside it, the diff capped by
 *   `capDiff`.
 *
 *   Every metadata value is validated at this boundary with the same patterns
 *   as `render-pr-review.ts`; a bad one exits 2 rather than being repaired.
 *
 * @outputs
 *   - `REFUTER_PROMPT` / `CHECKLIST_PROMPT` -- the fixed system prompts
 *   - `REFUTE_FINDINGS_MAX_BYTES` -- the byte cap on the refuter's review text
 *   - `trustFiles` -- files -> the trust-surface subset, sorted and deduped
 *   - `parseDiffSections` -- diff text -> per-file header path sets
 *   - `countBlockingFindings` -- reviews -> the number of P0/P1 finding lines
 *   - `planSecondPass` -- chunk reviews + diff sections -> the plan; when
 *     refute, `refute_findings` is the P0/P1 line count the refuter must match;
 *     `diff_truncated: true` when the diff exceeds `MAX_DIFF_BYTES`
 *   - `buildRefuteRequest` / `buildChecklistRequest` -- the two request bodies
 *   - CLI: always writes `$CHUNK_DIR/second-pass.json`; `refute-request.json`
 *     iff refute, `checklist-request.json` iff checklist; one stderr line
 *     `render-second-pass: refute=<bool> checklist=<bool>`; exit 0. Invalid
 *     environment: exit 2 with one stderr line
 *
 * @dependencies
 *   - ./render-pr-review -- `capDiff`, `DEFAULT_ENGINE_MODEL`, `EngineRequest`
 *   - ./post-pr-review -- `readChunkReplies`, `parseVerdict`
 */
import { traced } from "../../src/log";
import { ANY_BLOCKING_GRADE, readChunkReplies, reviewVerdict } from "./post-pr-review";
import {
	capDiff,
	DEFAULT_ENGINE_MODEL,
	type EngineRequest,
	MAX_DIFF_BYTES,
} from "./render-pr-review";

/** The refuter's fixed system prompt (exact). */
export const REFUTER_PROMPT = `You are the adversarial second reviewer for a pull request. The user message holds the first reviewer's findings
and the diff. For EVERY P0 or P1 finding in the first review, try to refute it using only the diff: is the cited
file:line real, does the code actually do what the finding claims, and is it a defect in what this change does
(not a hardening wish or scope expansion)? Default to REFUTED if you cannot confirm it from the diff. Reply in
markdown only: one line per P0/P1 finding, \`- UPHELD: <finding in a few words> -- <reason>\` or
\`- REFUTED: <finding in a few words> -- <reason>\`, then a final line exactly \`verdict: fix-first\` if any finding is
UPHELD, else exactly \`verdict: approve\`. No praise, facts only.`;

/** The trust-surface checklist's fixed system prompt (exact). */
export const CHECKLIST_PROMPT = `You check a pull request diff that touches the factory's trust surface against a fixed checklist. For each item
answer pass, fail, or n/a (the diff does not touch what the item governs), with file:line evidence from the diff:
1. A job that runs repository or agent content holds at most the engine key: no forge token, no OIDC, no secrets.
2. No target repository tree is checked out inside the factory's own checkout or workspace import path.
3. No \`\${{ }}\` expression is interpolated inside a \`run:\` script body.
4. Every push is fully qualified on both sides and never forced (\`--force\`, \`+refspec\`, \`--mirror\`).
5. Ancestry is re-proved before any push.
6. A credentialed job runs only under \`workflow_dispatch\` (D23). Exception: a workflow generated by enroll-app for the
   app tag rail runs owner-cut, merged code at a tag, outside D23's PR-editable surface, so item 6 is n/a for it
   only when ALL of these hold: it carries the stamp line \`# Written by enroll-app; re-run it to regenerate.\`;
   its \`on:\` has no event other than \`push\` and \`workflow_dispatch\`; \`on.push\` lists \`tags\` only (no
   \`branches\`, no \`branches-ignore\`, no \`paths\` without \`tags\`); and every job that receives secrets carries an
   \`if:\` admitting only the app's release tag form. If any other event is present (\`pull_request\`,
   \`pull_request_target\`, \`push\` to branches, \`schedule\`, \`issue_comment\`, \`workflow_run\`, or any other), the
   exception does not apply and item 6 is judged normally. Either way, items 1 and 2 still apply to it in full.
7. Artifact download directories are distinct and outside every import path.
Reply in markdown only: a table \`| # | item | result | evidence |\` with one row per item, then a final line exactly
\`verdict: fix-first\` if any item is fail, else exactly \`verdict: approve\`. No praise, facts only.`;

/** The byte cap on the pass-1 review text carried to the refuter. */
export const REFUTE_FINDINGS_MAX_BYTES = 20000;

const TRUST_PREFIXES = [".forgejo/workflows/", "src/hooks/", "scripts/actions/"];
const TRUST_EXACT = new Set(["src/results/change-ingest.ts", "src/results/bundle-inspector.ts"]);

/** The bounded metadata the renderer accepts, before validation. */
export interface SecondPassEnv {
	REPO?: string;
	PR?: string;
	HEAD_SHA?: string;
	BASE_SHA?: string;
	ENGINE_MODEL?: string;
}

/** One pass-1 chunk's extracted review text. */
export interface SecondPassPart {
	review: string;
}

/** One `diff --git` file section's header paths; `unparseable` fails closed. */
export interface DiffSection {
	paths: string[];
	unparseable: boolean;
}

/** The marker listed in `trust_files` when a diff header cannot be parsed. */
export const UNPARSEABLE_MARKER = "<unparseable diff header>";

/** The plan written to `second-pass.json`. */
export interface SecondPassPlan {
	refute: boolean;
	checklist: boolean;
	trust_files: string[];
	refute_skipped?: string;
	refute_findings?: number;
	diff_truncated?: boolean;
}

/** Thrown for an invalid environment; the CLI turns it into exit 2. */
export class SecondPassEnvError extends Error {}

const REPO_PATTERN = /^[A-Za-z0-9_.-]+\/[A-Za-z0-9_.-]+$/;
const SHA_PATTERN = /^[0-9a-fA-F]{7,40}$/;
const ITEM_PATTERN = /^[1-9][0-9]*$/;

function trustFilesImpl(files: string[]): string[] {
	const matched = files.filter(
		(file) => TRUST_EXACT.has(file) || TRUST_PREFIXES.some((prefix) => file.startsWith(prefix)),
	);
	return [...new Set(matched)].sort();
}

export const trustFiles = traced("actions.secondPass.trustFiles", trustFilesImpl);

const HEADER_PREFIXES = [
	"rename from ",
	"rename to ",
	"copy from ",
	"copy to ",
	"--- a/",
	"+++ b/",
] as const;

function sectionOf(lines: string[]): DiffSection {
	const paths: string[] = [];
	let quoted = false;
	for (const line of lines) {
		for (const prefix of HEADER_PREFIXES) {
			if (line.startsWith(prefix)) paths.push(line.slice(prefix.length));
		}
		if (line.startsWith('--- "') || line.startsWith('+++ "')) quoted = true;
	}
	if (paths.length === 0) {
		const header = (lines[0] ?? "").slice("diff --git ".length);
		const parts = header.split(" b/");
		if (parts.length === 2 && parts[0]?.startsWith("a/")) {
			paths.push(parts[0].slice(2), parts[1] ?? "");
		} else if (header.startsWith('"')) {
			quoted = true;
		}
	}
	if (paths.some((path) => path.startsWith('"'))) quoted = true;
	const found = paths.filter((path) => path !== "");
	return { paths: found, unparseable: quoted || found.length === 0 };
}

function parseDiffSectionsImpl(diff: string): DiffSection[] {
	const sections: string[][] = [];
	for (const line of diff.split("\n")) {
		if (line.startsWith("diff --git ")) sections.push([line]);
		else sections.at(-1)?.push(line);
	}
	// A non-empty diff with no `diff --git` header cannot be attributed to a path: fail closed.
	if (sections.length === 0 && diff.trim() !== "") return [{ paths: [], unparseable: true }];
	return sections.map(sectionOf);
}

export const parseDiffSections = traced(
	"actions.secondPass.parseDiffSections",
	parseDiffSectionsImpl,
	{
		redact: { args: [0], result: true },
	},
);

const joinReviews = (reviews: string[]): string => reviews.join("\n\n---\n\n");

function fixFirstReviews(parts: SecondPassPart[]): string[] {
	return parts
		.filter((part) => reviewVerdict(part.review) === "fix-first")
		.map((part) => part.review);
}

/**
 * The number of lines across the reviews that name P0 or P1, each line counted
 * once: the same rule the severity rule blocks on (post-pr-review.ts
 * ANY_BLOCKING_GRADE), so the refuter owes one `- REFUTED:` per blocking line
 * whatever marker the reviewer used. A line that names a grade without being
 * a finding inflates the count, which only fails closed.
 */
function countBlockingFindingsImpl(reviews: string[]): number {
	return reviews
		.flatMap((review) => review.split("\n"))
		.filter((line) => ANY_BLOCKING_GRADE.test(line)).length;
}

export const countBlockingFindings = traced(
	"actions.secondPass.countBlockingFindings",
	countBlockingFindingsImpl,
	{ redact: { args: [0] } },
);

function planSecondPassImpl(
	parts: SecondPassPart[],
	sections: DiffSection[],
	diffBytes: number,
): SecondPassPlan {
	const unparseable = sections.some((section) => section.unparseable);
	const trust = trustFiles(
		sections.flatMap((section) => (trustFiles(section.paths).length > 0 ? section.paths : [])),
	);
	const trust_files = unparseable ? [...trust, UNPARSEABLE_MARKER] : trust;
	const reviews = fixFirstReviews(parts);
	const tooBig =
		new TextEncoder().encode(joinReviews(reviews)).byteLength > REFUTE_FINDINGS_MAX_BYTES;
	const plan: SecondPassPlan = {
		refute: reviews.length > 0 && !tooBig,
		checklist: trust_files.length > 0,
		trust_files,
	};
	if (plan.refute) plan.refute_findings = countBlockingFindings(reviews);
	if (reviews.length > 0 && tooBig) {
		plan.refute_skipped = `findings exceed ${REFUTE_FINDINGS_MAX_BYTES} bytes`;
	}
	if (diffBytes > MAX_DIFF_BYTES) plan.diff_truncated = true;
	return plan;
}

export const planSecondPass = traced("actions.secondPass.plan", planSecondPassImpl, {
	redact: { args: [0, 1] },
});

/** Validate the bounded metadata; returns the model and both SHAs. */
function validate(env: SecondPassEnv): { model: string; headSha: string; baseSha: string } {
	if (!REPO_PATTERN.test(env.REPO ?? "")) throw new SecondPassEnvError("REPO must be owner/repo");
	if (!ITEM_PATTERN.test(env.PR ?? ""))
		throw new SecondPassEnvError("PR must be a positive integer");
	const headSha = env.HEAD_SHA ?? "";
	if (!SHA_PATTERN.test(headSha)) {
		throw new SecondPassEnvError("HEAD_SHA must be 7-40 hex characters");
	}
	const baseSha = env.BASE_SHA ?? "";
	if (!SHA_PATTERN.test(baseSha)) {
		throw new SecondPassEnvError("BASE_SHA must be 7-40 hex characters");
	}
	const model =
		env.ENGINE_MODEL && env.ENGINE_MODEL !== "" ? env.ENGINE_MODEL : DEFAULT_ENGINE_MODEL;
	return { model, headSha, baseSha };
}

/** Wrap untrusted `body` in a backtick fence longer than any run inside it (min 3). */
function fence(info: string, body: string): string {
	const longest = Math.max(0, ...(body.match(/`+/g) ?? []).map((run) => run.length));
	const ticks = "`".repeat(Math.max(3, longest + 1));
	return `${ticks}${info}\n${body}\n${ticks}`;
}

function request(env: SecondPassEnv, system: string, diff: Uint8Array, reviews?: string[]) {
	const { model, headSha, baseSha } = validate(env);
	const first =
		reviews === undefined ? "" : `First review:\n${fence("text", joinReviews(reviews))}\n\n`;
	const user = `Base sha: ${baseSha}\nHead sha: ${headSha}\n\n${first}${fence("diff", capDiff(diff))}`;
	const built: EngineRequest = {
		model,
		reasoning_effort: "high",
		max_completion_tokens: 4000,
		messages: [
			{ role: "system", content: system },
			{ role: "user", content: user },
		],
	};
	return built;
}

function buildRefuteRequestImpl(
	env: SecondPassEnv,
	reviews: string[],
	diff: Uint8Array,
): EngineRequest {
	return request(env, REFUTER_PROMPT, diff, reviews);
}

export const buildRefuteRequest = traced(
	"actions.secondPass.buildRefuteRequest",
	buildRefuteRequestImpl,
	{
		redact: { args: [0, 1, 2], result: true },
	},
);

function buildChecklistRequestImpl(env: SecondPassEnv, diff: Uint8Array): EngineRequest {
	return request(env, CHECKLIST_PROMPT, diff);
}

export const buildChecklistRequest = traced(
	"actions.secondPass.buildChecklistRequest",
	buildChecklistRequestImpl,
	{ redact: { args: [0, 1], result: true } },
);

if (import.meta.main) {
	const env = process.env as SecondPassEnv;
	const chunkDir = process.env.CHUNK_DIR ?? "";
	const diffFile = process.env.DIFF_FILE ?? "";
	try {
		if (chunkDir === "") throw new SecondPassEnvError("CHUNK_DIR is required");
		if (diffFile === "") throw new SecondPassEnvError("DIFF_FILE is required");
		validate(env);
		const parts = await readChunkReplies(chunkDir);
		const diff = new Uint8Array(await Bun.file(diffFile).arrayBuffer());
		const plan = planSecondPass(
			parts,
			parseDiffSections(new TextDecoder().decode(diff)),
			diff.byteLength,
		);
		if (plan.refute) {
			const reviews = fixFirstReviews(parts);
			await Bun.write(
				`${chunkDir}/refute-request.json`,
				JSON.stringify(buildRefuteRequest(env, reviews, diff)),
			);
		}
		if (plan.checklist) {
			await Bun.write(
				`${chunkDir}/checklist-request.json`,
				JSON.stringify(buildChecklistRequest(env, diff)),
			);
		}
		await Bun.write(`${chunkDir}/second-pass.json`, JSON.stringify(plan));
		process.stderr.write(`render-second-pass: refute=${plan.refute} checklist=${plan.checklist}\n`);
	} catch (error) {
		if (error instanceof SecondPassEnvError) {
			process.stderr.write(`render-second-pass: ${error.message}\n`);
			process.exitCode = 2;
		} else {
			throw error;
		}
	}
}
